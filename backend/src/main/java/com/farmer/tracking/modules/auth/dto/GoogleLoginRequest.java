package com.farmer.tracking.modules.auth.dto;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;

/**
 * Authorization code returned by Google to the browser, to be exchanged by the backend.
 */
public class GoogleLoginRequest {

    @NotBlank(message = "Authorization code is required")
    @Size(max = 2048, message = "Authorization code is too long")
    private String code;

    @NotBlank(message = "Redirect URI is required")
    @Size(max = 512, message = "Redirect URI is too long")
    private String redirectUri;

    /** PKCE verifier generated by the browser when it started the sign-in. */
    @NotBlank(message = "Code verifier is required")
    @Pattern(regexp = "[A-Za-z0-9._~-]{43,128}", message = "Code verifier is invalid")
    private String codeVerifier;

    public GoogleLoginRequest() {}

    public String getCode() {
        return code;
    }

    public void setCode(String code) {
        this.code = code;
    }

    public String getRedirectUri() {
        return redirectUri;
    }

    public void setRedirectUri(String redirectUri) {
        this.redirectUri = redirectUri;
    }

    public String getCodeVerifier() {
        return codeVerifier;
    }

    public void setCodeVerifier(String codeVerifier) {
        this.codeVerifier = codeVerifier;
    }
}
